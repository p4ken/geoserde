use serde::de::value::MapAccessDeserializer;

use crate::v0_6_1::fgb::coord::CoordIter;

pub struct GeometryDeserializer<'de> {
    geom: flatgeobuf::Geometry<'de>,
    geom_type: flatgeobuf::GeometryType,
}
