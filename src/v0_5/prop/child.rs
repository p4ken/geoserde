// parent.child
// parent[i].child
pub struct ChildSerializer<'a, S> {
    sink: &'a mut S,
    key: &'static str,
}

impl<'a, S> ChildSerializer<'a, S> {
    pub fn new(sink: &'a mut S) -> Self {
        Self { sink, key: "" }
    }
}

